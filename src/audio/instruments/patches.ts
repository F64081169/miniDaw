export const PATCH_BY_ID = new Map(PATCHES.map((p) => [p.id, p]));

export function getPatch(id: string | undefined): PatchDef {
  return (id && PATCH_BY_ID.get(id)) || PATCH_BY_ID.get('piano.grand')!;
}

export function patchesByCategory(cat: PatchCategory): PatchDef[] {
  return PATCHES.filter((p) => p.category === cat);
}

export function defaultParams(patch: PatchDef): Record<string, number> {
  return Object.fromEntries(patch.controls.map((ctl) => [ctl.id, ctl.default]));
}

export function isDrumPatch(id: string | undefined): boolean {
  return getPatch(id).engine === 'drums';
}
