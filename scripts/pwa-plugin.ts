// Vite plugin for the installable offline build (multi-file build only):
// adds the manifest / home-screen tags to index.html and writes sw.js, a service worker
// that precaches every file of this build so the app opens and runs without a network.

import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import type { Plugin } from 'vite';

const HEAD_TAGS = `
    <link rel="manifest" href="./manifest.webmanifest" />
    <meta name="theme-color" content="#171b21" />
    <link rel="apple-touch-icon" href="./icons/apple-touch-icon.png" />
    <meta name="apple-mobile-web-app-capable" content="yes" />
    <meta name="mobile-web-app-capable" content="yes" />
    <meta name="apple-mobile-web-app-title" content="miniDaw" />
    <meta name="apple-mobile-web-app-status-bar-style" content="black-translucent" />`;

function listFiles(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? listFiles(path) : [path];
  });
}

function serviceWorker(version: string, files: string[]): string {
  return `// Generated by scripts/pwa-plugin.ts — precaches build ${version}.
const CACHE = 'minidaw-${version}';
const FONTS = 'minidaw-fonts';
const FILES = ${JSON.stringify(files)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(FILES)));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE && k !== FONTS).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('message', (event) => {
  if (event.data === 'skip-waiting') self.skipWaiting();
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.hostname === 'fonts.googleapis.com' || url.hostname === 'fonts.gstatic.com') {
    // fonts: use the cached copy, refresh it when online
    event.respondWith(
      caches.open(FONTS).then(async (cache) => {
        const hit = await cache.match(req);
        const fresh = fetch(req)
          .then((res) => {
            if (res.ok || res.type === 'opaque') cache.put(req, res.clone());
            return res;
          })
          .catch(() => hit || Response.error());
        return hit || fresh;
      }),
    );
    return;
  }
  if (url.origin !== self.location.origin) return;
  // the app shell and its files come from this build's cache, so the app works offline
  const key = req.mode === 'navigate' ? new URL('./', self.location.href).href : req;
  event.respondWith(caches.match(key, { cacheName: CACHE, ignoreSearch: true }).then((hit) => hit || fetch(req)));
});
`;
}

export function pwa(): Plugin {
  let publicDir = 'public';
  return {
    name: 'minidaw-pwa',
    apply: 'build',
    enforce: 'post',
    configResolved(config) {
      publicDir = config.publicDir;
    },
    transformIndexHtml(html) {
      return html.replace('</title>', `</title>${HEAD_TAGS}`);
    },
    generateBundle(_options, bundle) {
      const hash = createHash('sha256');
      const files = new Set<string>(['./']);
      for (const [name, item] of Object.entries(bundle)) {
        files.add(name);
        hash.update(name);
        hash.update(item.type === 'chunk' ? item.code : typeof item.source === 'string' ? item.source : Buffer.from(item.source));
      }
      if (publicDir) {
        for (const path of listFiles(publicDir)) {
          const name = relative(publicDir, path).split(sep).join('/');
          files.add(name);
          hash.update(name);
          hash.update(readFileSync(path));
        }
      }
      const version = hash.digest('hex').slice(0, 12);
      const list = [...files].filter((f) => f !== 'sw.js').sort();
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: serviceWorker(version, list) });
    },
  };
}
